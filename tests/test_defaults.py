"""
Test that the shell profiles stay in sync with nanochat/defaults.py (the SSOT).

Python is canonical: runs/profiles.sh is generated by `python -m nanochat.defaults emit-shell`,
so every PROFILE_* knob must round-trip into a bash assignment with an unchanged value.

Run: python -m pytest tests/test_defaults.py -q
"""
import shlex
import subprocess
import sys
from pathlib import Path

import pytest
import torch

from nanochat import defaults
from nanochat.gpt import GPT, GPTConfig

REPO_ROOT = Path(__file__).resolve().parents[1]
PROFILES_SH = REPO_ROOT / "runs" / "profiles.sh"
REGENERATE = "python -m nanochat.defaults emit-shell > runs/profiles.sh"


def _parse_shell_assignments(text):
    """Parse `export NAME=value` lines into {NAME: value}, undoing shell quoting."""
    assignments = {}
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, value = line.removeprefix("export ").partition("=")
        assignments[name] = " ".join(shlex.split(value))
    return assignments


def _expected_assignments(profile_name, profile):
    return {f"{profile_name}_{knob}".upper(): str(value) for knob, value in profile.items()}


@pytest.mark.parametrize("profile_name", sorted(defaults.PROFILES))
def test_emitted_shell_vars_match_profile(profile_name):
    expected = _expected_assignments(profile_name, defaults.PROFILES[profile_name])
    emitted = _parse_shell_assignments(defaults.emit_shell())
    assert {name: emitted.get(name) for name in expected} == expected


def test_emitted_shell_exports_nothing_beyond_the_profiles():
    expected = set()
    for profile_name, profile in defaults.PROFILES.items():
        expected |= set(_expected_assignments(profile_name, profile))
    assert set(_parse_shell_assignments(defaults.emit_shell())) == expected


def test_checked_in_profiles_sh_is_up_to_date():
    assert PROFILES_SH.read_text() == defaults.emit_shell(), f"stale runs/profiles.sh, regenerate: {REGENERATE}"


def test_emit_shell_subcommand_prints_the_profiles():
    completed = subprocess.run(
        [sys.executable, "-m", "nanochat.defaults", "emit-shell"],
        cwd=REPO_ROOT, capture_output=True, text=True, check=True,
    )
    assert completed.stdout == defaults.emit_shell()


def test_unknown_subcommand_is_refused_with_usage():
    completed = subprocess.run(
        [sys.executable, "-m", "nanochat.defaults", "--check-profiles"],
        cwd=REPO_ROOT, capture_output=True, text=True,
    )
    assert completed.returncode == 2 and "usage: python -m nanochat.defaults emit-shell" in completed.stderr


def test_boolean_knob_is_refused_because_a_flag_has_no_value_to_export(monkeypatch):
    monkeypatch.setitem(defaults.PROFILES, "probe", {"fp8": True})
    with pytest.raises(TypeError, match=r"profile 'probe' knob 'fp8' is a bool"):
        defaults.emit_shell()


def test_knob_value_needing_quotes_stays_one_shell_token(monkeypatch):
    monkeypatch.setitem(defaults.PROFILES, "probe", {"window_pattern": "S L"})
    emitted = _parse_shell_assignments(defaults.emit_shell())
    assert emitted["PROBE_WINDOW_PATTERN"] == "S L"


def test_cli_batch_size_default_stays_high_while_the_mac_profile_lowers_it():
    assert (defaults.DEFAULT_DEVICE_BATCH_SIZE, defaults.PROFILE_RUNCPU["device_batch_size"]) == (32, 8)


def test_global_cli_defaults_are_published_for_the_train_scripts():
    cli_defaults = (defaults.DEFAULT_DEPTH, defaults.DEFAULT_SEQ_LEN, defaults.DEFAULT_DEVICE_BATCH_SIZE)
    assert cli_defaults == (20, 2048, 32)


def test_memory_fit_knobs_are_published_for_the_memory_helper():
    assert (defaults.MEMORY_FIT_MARGIN, defaults.MEMORY_ACTIVATION_FUDGE) == (0.6, 1.5)


@pytest.mark.parametrize("knob", ["core_metric_every", "sample_every"])
def test_runcpu_profile_covers_every_base_train_knob_the_mac_run_overrides(knob):
    assert knob in defaults.PROFILE_RUNCPU


def test_model_config_defaults_come_from_the_ssot():
    config = GPTConfig()
    assert (config.vocab_size, config.sequence_len) == (defaults.VOCAB_SIZE, defaults.DEFAULT_SEQ_LEN)


def test_forward_saturates_logits_at_the_ssot_softcap():
    config = GPTConfig(sequence_len=16, vocab_size=64, n_layer=1, n_head=1,
                       n_kv_head=1, n_embd=64, window_pattern="L")
    model = GPT(config)
    with torch.no_grad():
        model.lm_head.weight.mul_(1000) # drive the raw logits far past the cap
        logits = model(torch.randint(0, config.vocab_size, (1, config.sequence_len)))
    # saturated tanh reaches the cap exactly in fp32, so this pins the value itself
    assert logits.abs().max().item() == pytest.approx(defaults.LOGIT_SOFTCAP, rel=1e-3)
