"""
Canonical defaults for nanochat: one owner for every run knob (SSOT).

Python is the single source of truth. The shell side obtains the same values via
`python -m nanochat.defaults emit-shell`, whose output is checked in as
runs/profiles.sh. On any conflict Python wins: regenerate the shell file.

Run as:
    python -m nanochat.defaults emit-shell > runs/profiles.sh
"""

import shlex
import sys

# -----------------------------------------------------------------------------
# Model / shared constants

VOCAB_SIZE = 32768 # 2**15, matches the --vocab-size default of scripts/tok_train.py
DEFAULT_SEQ_LEN = 2048
LOGIT_SOFTCAP = 15 # logits are squashed into [-LOGIT_SOFTCAP, LOGIT_SOFTCAP]

# Memory auto-fit aims to use at most this fraction of available device memory.
# Overridable at run time via the NANOCHAT_MEMORY_FIT_MARGIN environment variable.
MEMORY_FIT_MARGIN = 0.6

# Conservative multiplier on the estimated forward/backward activation bytes:
# the estimate is order-of-magnitude, so it errs on the side of a smaller batch.
MEMORY_ACTIVATION_FUDGE = 1.5

# Global argparse defaults for the train scripts. Profiles may lower them; the
# CLI defaults stay high so GPU runs are unchanged by the Mac-oriented profiles.
DEFAULT_DEVICE_BATCH_SIZE = 32
DEFAULT_DEPTH = 20

# -----------------------------------------------------------------------------
# Run profiles: the knobs runs/*.sh pass on the command line.
#
# Values are int or str only. Boolean switches such as --fp8 stay literal in the
# run script: a flag carries no value to export, and bash has no typed values.

PROFILE_RUNCPU = {
    "depth": 6,
    "head_dim": 64,
    "window_pattern": "L",
    "max_seq_len": 512,
    "device_batch_size": 8, # lower than DEFAULT_DEVICE_BATCH_SIZE: 32 OOMs on MPS
    "total_batch_size": 16384,
    "num_iterations": 5000,
    "eval_every": 100,
    "eval_tokens": 524288,
    "core_metric_every": -1, # CORE metric is too slow to be useful on a Mac
    "sample_every": 100,
    "eval_device_batch_size": 1,
}

PROFILE_SPEEDRUN = {
    "depth": 24,
    "device_batch_size": 16,
    "target_param_data_ratio": 8,
    "eval_device_batch_size": 16,
}

PROFILES = {
    "runcpu": PROFILE_RUNCPU,
    "speedrun": PROFILE_SPEEDRUN,
}

# -----------------------------------------------------------------------------
# Shell emission


def shell_var_name(profile_name, knob):
    """Shell variable a profile knob is exported as, e.g. ('runcpu', 'depth') -> RUNCPU_DEPTH."""
    return f"{profile_name}_{knob}".upper()


def _shell_value(profile_name, knob, value):
    if isinstance(value, bool) or not isinstance(value, (int, str)):
        raise TypeError(
            f"profile '{profile_name}' knob '{knob}' is a {type(value).__name__}, "
            f"but a shell profile knob must be an int or a str "
            f"(bash has no typed values, and a boolean flag has no value to export). "
            f"Give the knob an int or str value, or keep the flag literal in runs/*.sh."
        )
    return shlex.quote(str(value))


def emit_shell():
    """Bash exports for every PROFILE_* knob, as checked in to runs/profiles.sh."""
    lines = [
        "# Generated by: python -m nanochat.defaults emit-shell",
        "# Canonical source: nanochat/defaults.py (PROFILE_RUNCPU, PROFILE_SPEEDRUN).",
        "# Do not edit by hand: change defaults.py and regenerate. Python wins on conflict.",
        "# shellcheck shell=bash",
    ]
    for profile_name, profile in PROFILES.items():
        lines.append("")
        lines.append(f"# profile: {profile_name}")
        for knob, value in profile.items():
            name = shell_var_name(profile_name, knob)
            lines.append(f"export {name}={_shell_value(profile_name, knob, value)}")
    return "\n".join(lines) + "\n"


def main(argv):
    if argv[1:] != ["emit-shell"]:
        print("usage: python -m nanochat.defaults emit-shell", file=sys.stderr)
        return 2
    sys.stdout.write(emit_shell())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
